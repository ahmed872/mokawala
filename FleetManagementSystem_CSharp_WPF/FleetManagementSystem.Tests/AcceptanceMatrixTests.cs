    private static async Task<IReadOnlyList<Dictionary<string, object>>> Rows(AcceptanceHarness harness, string reportType, int? vehicleId = null)
    {
        var report = await harness.ReportingService.GenerateReportAsync(new ReportFilterDto
        {
            ReportType = reportType,
            VehicleId = vehicleId
        });

        return report.Data;
    }

    private static async Task<(Dictionary<string, object> Row, string Plate)> FirstVehicleRow(AcceptanceHarness harness, SeedData seed)
    {
        var row = (await Rows(harness, "vehicles")).First(r => Text(r, "رقم السيارة") == seed.Vehicle.PlateNumber);
        return (row, seed.Vehicle.PlateNumber);
    }

    private static string Text(Dictionary<string, object> row, string column) =>
        row.TryGetValue(column, out var value) ? value?.ToString() ?? string.Empty : string.Empty;

    private static decimal Number(Dictionary<string, object> row, string column)
    {
        if (!row.TryGetValue(column, out var value) || value is null)
        {
            return 0;
        }

        return Convert.ToDecimal(value);
    }

