    [Fact]
    public async Task ReportingAndAlertAcceptanceMatrix_OneHundredEightyThreeChecks_Pass()
    {
        await using var harness = await AcceptanceHarness.CreateAsync();
        var seed = await SeedBusinessDataAsync(harness);
        var checks = new List<AcceptanceCheck>();

        var expectations = BuildReportExpectations();
        foreach (var expectation in expectations)
        {
            checks.Add(new($"{expectation.Type} title", async () =>
            {
                var report = await harness.ReportingService.GenerateReportAsync(new ReportFilterDto { ReportType = expectation.Type });
                Assert.Equal(expectation.Title, report.ReportTitle);
            }));

            checks.Add(new($"{expectation.Type} generated by system", async () =>
            {
                var report = await harness.ReportingService.GenerateReportAsync(new ReportFilterDto { ReportType = expectation.Type });
                Assert.Equal("System", report.GeneratedBy);
            }));

            checks.Add(new($"{expectation.Type} generated date", async () =>
            {
                var before = DateTime.UtcNow.AddSeconds(-5);
                var report = await harness.ReportingService.GenerateReportAsync(new ReportFilterDto { ReportType = expectation.Type });
                Assert.True(report.GeneratedDate >= before);
            }));

            checks.Add(new($"{expectation.Type} data list", async () =>
            {
                var report = await harness.ReportingService.GenerateReportAsync(new ReportFilterDto { ReportType = expectation.Type });
                Assert.NotNull(report.Data);
            }));

            checks.Add(new($"{expectation.Type} future filter", async () =>
            {
                var report = await harness.ReportingService.GenerateReportAsync(new ReportFilterDto
                {
                    ReportType = expectation.Type,
                    StartDate = DateTime.Today.AddYears(20),
                    EndDate = DateTime.Today.AddYears(20).AddDays(1)
                });

                Assert.Empty(report.Data);
            }));

            checks.Add(new($"{expectation.Type} invalid range rejected", async () =>
            {
                await Assert.ThrowsAsync<InvalidOperationException>(() => harness.ReportingService.GenerateReportAsync(new ReportFilterDto
                {
                    ReportType = expectation.Type,
                    StartDate = DateTime.Today,
                    EndDate = DateTime.Today.AddDays(-1)
                }));
            }));

            foreach (var column in expectation.Columns)
            {
                checks.Add(new($"{expectation.Type} column {column}", async () =>
                {
                    var report = await harness.ReportingService.GenerateReportAsync(new ReportFilterDto { ReportType = expectation.Type });
                    Assert.Contains(column, report.Columns);
                }));
            }
        }

        checks.AddRange(BuildDataChecks(harness, seed));

        Assert.Equal(160, checks.Count);

        for (var index = 0; index < checks.Count; index++)
        {
            try
            {
                await checks[index].Execute();
            }
            catch (Exception ex)
            {
                throw new InvalidOperationException($"Acceptance check {index + 1:000} failed: {checks[index].Name}", ex);
            }
        }
    }

